'use strict';
const assert = require('node:assert/strict');
const E = require('./engine.js');
const C = require('./codec.js');
const F = require('./team_info.js');
(async () => {
let assertions = 0;
function check(value, message) { assert.ok(value, message); assertions++; }
function equal(a, b, message) { assert.deepEqual(a, b, message); assertions++; }
const doc = E.sample();
equal(E.validate(doc), [], 'example is structurally valid');
let state = E.createState(), run = E.derive(doc, state);
equal(run.ready.map(m => m.id), ['q1', 'q2', 'q3', 'q4']);
equal(run.starts.get('s1').map(t => t.startRank), [1, 2, 3, 4, 5, 6, 7, 8], 'start layer assigns unique rank');
check(run.previews.has('match:q1:win') && run.previews.has('match:q1:lose'));
check(run.displayInputs('result:a0')[0].token.preview, 'advance result displays A/B');
check(!run.results.has('a0') && !run.starts.has('s2'), 'preview never fills result or next stage');
check(E.step(doc, state, 't1').ok);
run = E.derive(doc, state);
equal(run.results.get('a0').id, 't1');
check(!run.results.has('e0'), 'merged result group waits for all its confirmed inputs');
check(!run.outputs.has('result:a0') && !run.starts.has('s2'), 'advance waits for whole result layer');
for (let i = 0; i < 3; i++) check(E.step(doc, state).ok);
run = E.derive(doc, state);
equal(run.activeStage, 's2');
equal(run.starts.get('s2').length, 4);
check(run.displayInputs('match:final').every(row => row.token?.preview));
check(!run.ready.some(m => m.id === 'final'), 'A/B-only final is not ready');
check(E.step(doc, state).ok);
run = E.derive(doc, state);
equal(run.matches.get('final').teams.length, 1, 'one confirmed plus one preview still not ready');
check(!run.ready.some(m => m.id === 'final'));
for (let i = 0; i < 3; i++) check(E.step(doc, state).ok);
run = E.derive(doc, state);
check(run.complete);
equal(state.history.length, 8, 'exactly one completed match per step');
equal(new Set([...run.results.values()].filter(t => t.finalRank).map(t => t.id)).size, 8, 'each team settles once');
state.history.pop(); check(!E.derive(doc, state).complete, 'undo recomputes flow');
const teams = [{ id: 'a', seedRank: 1, stageRank: 2, liveRank: 3 }, { id: 'b', seedRank: 1, stageRank: 1, liveRank: 4 }, { id: 'c', seedRank: 1, stageRank: 1, liveRank: 2 }, { id: 'd', seedRank: 2, stageRank: 0, liveRank: 0 }];
equal(E.startSort(teams, ['seedRank', 'stageRank', 'liveRank'].map(key => ({ key, direction: 'asc' }))).map(t => t.id), ['c', 'b', 'a', 'd'], 'lexicographic ascending tiebreakers');
equal(E.startSort(teams, Array.from({ length: 3 }, () => ({ key: '', direction: 'asc' }))).map(t => t.id), ['a', 'b', 'c', 'd'], 'all empty is identity');
const reversed = E.copy(doc); reversed.stages[0].sort[0].direction = 'desc'; check(E.validate(reversed).some(i => i.code === 'SORT'));
const fanout = E.copy(doc); fanout.links.push({ id: 'extra', source: 'match:q1:win', target: 'result:e1' }); check(E.validate(fanout).some(i => i.code === 'FANOUT'));
const missing = E.copy(doc); missing.links = missing.links.filter(l => l.source !== 'match:q1:lose'); check(E.validate(missing).some(i => i.code === 'MATCH_OUTPUT'));
const cycle = E.copy(doc); cycle.links.push({ id: 'cycle', source: 'match:final:win', target: 'match:semi1' }); check(E.validate(cycle).some(i => i.code === 'CYCLE'));
const cross = E.copy(doc); cross.links.find(l => l.source === 'match:q1:win').target = 'match:final'; check(E.validate(cross).some(i => i.code === 'CROSS_STAGE'));
const finalAdvance = E.copy(doc); finalAdvance.results.find(r => r.id === 'p1').kind = 'advance'; check(E.validate(finalAdvance).some(i => i.code === 'ADVANCE'));
equal(E.parse(JSON.stringify(doc)), doc, '.csem round trip preserves graph');
assert.throws(() => E.parse('{"schema":"unknown"}')); assertions++;
assert.throws(() => E.parse(JSON.stringify({ ...doc, matches: null }))); assertions++;
const fifoTeams = F.parseTeamInfo(await C.decode(require('node:fs').readFileSync(`${__dirname}/fifo_queue.tinf`), 'teams'));
const fifoDoc = F.readSchedule(await C.decode(require('node:fs').readFileSync(`${__dirname}/fifo_queue.csem`)), fifoTeams);
equal(E.validate(fifoDoc), [], 'FIFO regression fixture is a valid graph');
equal(E.createState(fifoDoc).queue, ['first1', 'first2', 'first3', 'first4'], 'document-aware initialization enqueues all initial confirmed matches');
const fifoState = E.createState();
equal(E.derive(fifoDoc, fifoState).ready.map(m => m.id), ['first1', 'first2', 'first3', 'first4'], 'all initial confirmed matches enqueue together');
equal(E.step(fifoDoc, fifoState, 't1').match.id, 'first1');
equal(E.derive(fifoDoc, fifoState).ready.map(m => m.id), ['first2', 'first3', 'first4'], 'single confirmation and preview do not enqueue downstream');
equal(E.step(fifoDoc, fifoState, 't3').match.id, 'first2');
equal(E.derive(fifoDoc, fifoState).ready.map(m => m.id), ['first3', 'first4', 'downstream'], 'newly ready downstream appends after waiting matches regardless of storage order');
equal(fifoState.queue, ['first3', 'first4', 'downstream'], 'runtime state maintains a real FIFO');
const cachedState = E.copy(fifoState);
equal(E.derive(fifoDoc, fifoState).queue, fifoState.queue);
equal(E.derive(fifoDoc, fifoState).queue, fifoState.queue, 'repeated renders do not enqueue twice');
equal(fifoState, cachedState, 'derive does not mutate queue or history');
const legacy = { history: E.copy(fifoState.history) };
equal(E.derive(fifoDoc, legacy).queue, ['first3', 'first4', 'downstream'], 'history without cached queue replays enqueue events');
const invalidWinner = E.copy(fifoState);
check(!E.step(fifoDoc, fifoState, 't1').ok, 'invalid winner rejected for queue head');
equal(fifoState, invalidWinner, 'rejected step does not consume queue');
check(E.backStep(fifoDoc, fifoState));
equal(E.derive(fifoDoc, fifoState).queue, ['first2', 'first3', 'first4'], 'undo removes downstream that is no longer confirmed');
equal(E.step(fifoDoc, fifoState, 't4').match.id, 'first2', 'changing winner after undo still consumes same head');
equal(E.derive(fifoDoc, fifoState).queue, ['first3', 'first4', 'downstream'], 'redo appends downstream once');
equal(E.step(fifoDoc, fifoState, 't5').match.id, 'first3');
equal(E.step(fifoDoc, fifoState, 't7').match.id, 'first4');
equal(E.step(fifoDoc, fifoState, 't1').match.id, 'downstream');
check(E.derive(fifoDoc, fifoState).complete, 'FIFO fixture completes and settles all teams');
equal(fifoState.queue, [], 'completed matches leave no stale queue entries');
fifoState.history.pop();
equal(E.derive(fifoDoc, fifoState).queue, ['downstream'], 'direct history rewind invalidates cache and rebuilds FIFO');
equal(E.derive(fifoDoc, E.createState()).queue, ['first1', 'first2', 'first3', 'first4'], 'reset starts with fresh initial queue');
const crossStageState = E.createState();
for (let i = 0; i < 4; i++) check(E.step(doc, crossStageState).ok);
equal(crossStageState.queue, ['semi1', 'semi2'], 'next stage enqueues confirmed matches after full result layer');
const simultaneous = E.copy(crossStageState);
check(E.step(doc, simultaneous).ok); check(E.step(doc, simultaneous).ok);
equal(simultaneous.queue, ['final', 'bronze'], 'same-step newly ready siblings enqueue in stable storage order');
check(E.backStep(doc, crossStageState));
equal(crossStageState.queue, ['q4'], 'cross-stage undo restores old stage queue');
equal(E.derive(doc, crossStageState).activeStage, 's1');
console.log(`Graph engine: ${assertions} assertions passed.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
